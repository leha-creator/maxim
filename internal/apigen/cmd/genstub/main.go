// Command genstub генерирует реализацию apigen.StrictServerInterface, в которой
// каждая операция отвечает 501 not_implemented (R-7). Сервер бэкенда встраивает
// её глубже обработчиков модулей, поэтому реализованные операции её перекрывают.
//
//	go run ./cmd/genstub -in api.gen.go -out ../bootstrap/unimplemented.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"log"
	"os"
	"strings"
)

func main() {
	in := flag.String("in", "api.gen.go", "generated apigen file")
	out := flag.String("out", "", "output file")
	flag.Parse()
	if *out == "" {
		log.Fatal("genstub: -out is required")
	}
	methods, err := strictMethods(*in)
	if err != nil {
		log.Fatalf("genstub: %v", err)
	}
	src, err := render(methods)
	if err != nil {
		log.Fatalf("genstub: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("genstub: %v", err)
	}
}

// strictMethods возвращает имена методов StrictServerInterface в порядке объявления.
func strictMethods(path string) ([]string, error) {
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
	if err != nil {
		return nil, err
	}
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts := spec.(*ast.TypeSpec)
			if ts.Name.Name != "StrictServerInterface" {
				continue
			}
			iface, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				return nil, fmt.Errorf("StrictServerInterface is not an interface")
			}
			var names []string
			for _, m := range iface.Methods.List {
				for _, n := range m.Names {
					names = append(names, n.Name)
				}
			}
			return names, nil
		}
	}
	return nil, fmt.Errorf("StrictServerInterface not found in %s", path)
}

func render(methods []string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/apigen/cmd/genstub. DO NOT EDIT.

package bootstrap

import (
	"context"

	"github.com/leha-creator/maxim/internal/apigen"
	"github.com/leha-creator/maxim/internal/platform/apperr"
)

// unimplemented отвечает 501 not_implemented на каждую операцию (R-7).
type unimplemented struct{}

var _ apigen.StrictServerInterface = unimplemented{}
`)
	for _, m := range methods {
		opID := strings.ToLower(m[:1]) + m[1:]
		fmt.Fprintf(&b, `
func (unimplemented) %[1]s(context.Context, apigen.%[1]sRequestObject) (apigen.%[1]sResponseObject, error) {
	return nil, apperr.NotImplemented(%[2]q)
}
`, m, opID)
	}
	return format.Source(b.Bytes())
}
